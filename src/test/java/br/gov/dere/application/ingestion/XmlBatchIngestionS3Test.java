package br.gov.dere.application.ingestion;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import br.gov.dere.application.configuracao.ConfiguracaoIntegracao;
import br.gov.dere.application.configuracao.ConfiguracaoIntegracaoService;
import br.gov.dere.application.d1001.D1001XmlGenerator;
import br.gov.dere.application.transmissao.ArmazenamentoArtefatoTransmissao;
import br.gov.dere.application.upload.MemoriaArmazenamentoObjetoUpload;
import br.gov.dere.domain.contributor.D1001;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.mock.web.MockMultipartFile;

class XmlBatchIngestionS3Test {
  private JdbcTemplate jdbc;
  private MemoriaArmazenamentoObjetoUpload objetos;
  private ArmazenamentoArtefatoTransmissao artefatos;
  private XmlBatchIngestionService service;

  @BeforeEach
  void preparar() {
    var ds = new DriverManagerDataSource();
    ds.setDriverClassName("org.h2.Driver");
    ds.setUrl("jdbc:h2:mem:upload_s3_" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
    ds.setUsername("sa");
    ds.setPassword("");
    jdbc = new JdbcTemplate(ds);
    jdbc.execute("""
        CREATE TABLE dere_upload_batch (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id BIGINT NOT NULL,
          entity_id BIGINT NOT NULL,
          source_name VARCHAR(255) NOT NULL,
          source_object_uri VARCHAR(1000),
          file_count INT NOT NULL,
          valid_count INT NOT NULL,
          invalid_count INT NOT NULL,
          total_bytes BIGINT NOT NULL,
          created_at TIMESTAMP NOT NULL
        )
        """);
    jdbc.execute("""
        CREATE TABLE dere_entity (
          id BIGINT PRIMARY KEY,
          legal_name VARCHAR(255) NOT NULL
        )
        """);
    jdbc.update("INSERT INTO dere_entity(id, legal_name) VALUES (7, 'Entidade EFPC de teste'), (3, 'Fundação Família Previdência'), (5, 'Albaprev Instituto')");
    jdbc.execute("""
        CREATE TABLE dere_d1001_xml (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          upload_batch_id BIGINT NOT NULL,
          user_id BIGINT NOT NULL,
          entity_id BIGINT NOT NULL,
          source_name VARCHAR(255) NOT NULL,
          valid BOOLEAN NOT NULL,
          validation_message VARCHAR(2000),
          xml_content CLOB NOT NULL,
          created_at TIMESTAMP NOT NULL
        )
        """);
    objetos = new MemoriaArmazenamentoObjetoUpload("dataa-dere");
    artefatos = new ArmazenamentoArtefatoTransmissao(objetos);
    var integracao = mock(ConfiguracaoIntegracaoService.class);
    when(integracao.current()).thenReturn(new ConfiguracaoIntegracao(
        false, true, "https://api.receitafederal.gov.br/dere", "https://api.receitafederal.gov.br/token",
        "", null, false, "restricted-production", "nota_2026_001", 50, null));
    service = new XmlBatchIngestionService(jdbc, integracao, objetos, "local");
  }

  @Test
  void arquivaXmlOriginalEGravaUri() throws Exception {
    var xml = xmlD1001();
    var arquivo = new MockMultipartFile("file", "evento.xml", "application/xml", xml.getBytes(StandardCharsets.UTF_8));
    var resumo = service.ingest(arquivo, 1L, 7L);
    assertTrue(resumo.sourceObjectUri().startsWith("s3://dataa-dere/local/7-efpc-teste/"));
    assertTrue(resumo.sourceObjectUri().endsWith("-evento.xml"));
    assertEquals(xml, artefatos.ler(resumo.sourceObjectUri()));
    var xmlContent = jdbc.queryForObject("SELECT xml_content FROM dere_d1001_xml WHERE upload_batch_id=?", String.class, resumo.batchId());
    assertTrue(xmlContent.startsWith("s3://dataa-dere/local/7-efpc-teste/"));
    assertEquals(xml, artefatos.ler(xmlContent));
    var sourceUri = jdbc.queryForObject("SELECT source_object_uri FROM dere_upload_batch WHERE id=?", String.class, resumo.batchId());
    assertEquals(resumo.sourceObjectUri(), sourceUri);
  }

  @Test
  void arquivaCsvOriginalEXmlConvertido() throws Exception {
    var csv = """
        id;motExcl;nrProc;tpOper;tpAmb;aplicEmi;verAplic;nrInsc;iniValid;fimValid;novaValidadeIniValid;novaValidadeFimValid;regTribPrinc;regTribSecund;indNatTrib;tpAtividadeServFinanc;tpAtividadePlAssistSaude;tpAtividadePrognosticos;UFCredenc
        DeRE10011000000123456782026100112000000001;;;1;2;1;dere-poc/0.1;12345678;01/10/2026;;;;9;;0;;;;
        """;
    var arquivo = new MockMultipartFile("file", "contribuinte.csv", "text/csv", csv.getBytes(StandardCharsets.UTF_8));
    var resumo = service.ingest(arquivo, 1L, 3L);
    assertTrue(resumo.sourceObjectUri().startsWith("s3://dataa-dere/local/3-familia-previdencia/"));
    assertTrue(resumo.sourceObjectUri().endsWith("-contribuinte.csv"));
    assertEquals(csv, new String(objetos.lerBytes(resumo.sourceObjectUri()), StandardCharsets.UTF_8));
    var xmlContent = jdbc.queryForObject("SELECT xml_content FROM dere_d1001_xml WHERE upload_batch_id=?", String.class, resumo.batchId());
    assertTrue(xmlContent.startsWith("s3://dataa-dere/local/3-familia-previdencia/"));
    var xml = artefatos.ler(xmlContent);
    assertTrue(xml.contains("evtInfoContrib"));
    assertTrue(xml.contains("12345678"));
  }

  @Test
  void arquivaZipOriginalECadaXmlInterno() throws Exception {
    var xml = xmlD1001();
    var zip = zip(new Entrada("a.xml", xml));
    var arquivo = new MockMultipartFile("file", "lote.zip", "application/zip", zip);
    var resumo = service.ingest(arquivo, 1L, 5L);
    assertTrue(resumo.sourceObjectUri().endsWith("-lote.zip"));
    assertEquals(zip.length, objetos.lerBytes(resumo.sourceObjectUri()).length);
    var xmlContent = jdbc.queryForObject("SELECT xml_content FROM dere_d1001_xml WHERE upload_batch_id=?", String.class, resumo.batchId());
    assertTrue(xmlContent.startsWith("s3://dataa-dere/local/5-albaprev/"));
    assertEquals(xml, artefatos.ler(xmlContent));
  }

  private static String xmlD1001() throws Exception {
    return new D1001XmlGenerator().generate(new D1001(
        "DeRE10011000000123456782026100112000000001", 1, 2, "dere-poc/0.1", "12345678",
        LocalDate.of(2026, 10, 1), null, 9, List.of(), 0));
  }

  private static byte[] zip(Entrada... entradas) {
    var saida = new ByteArrayOutputStream();
    try (var zip = new ZipOutputStream(saida)) {
      for (var entrada : entradas) {
        zip.putNextEntry(new ZipEntry(entrada.nome()));
        zip.write(entrada.conteudo().getBytes(StandardCharsets.UTF_8));
        zip.closeEntry();
      }
    } catch (Exception ex) {
      throw new IllegalStateException(ex);
    }
    return saida.toByteArray();
  }

  private record Entrada(String nome, String conteudo) {}
}
